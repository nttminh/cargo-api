import { randomBytes } from 'node:crypto';
import { NestExpressApplication } from '@nestjs/platform-express';
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger';
import type { Request, Response } from 'express';

/**
 * Scalar API reference bundle, pinned with Subresource Integrity so the docs page can't change
 * (or be tampered with) unless we bump both values together. To upgrade:
 *   curl -s <url> | openssl dgst -sha384 -binary | openssl base64 -A
 */
const SCALAR_BUNDLE = {
  src: 'https://cdn.jsdelivr.net/npm/@scalar/api-reference@1.83.0/dist/browser/standalone.js',
  integrity: 'sha384-Z2Wz4L/5mCSEGTCpHPw3JIN6+eRxpIwq2sE2QfGtP+hmmwcgJKNVK9zBbfnbjlKN',
};

/**
 * OpenAPI spec (generated by @nestjs/swagger) rendered with Scalar.
 *   GET /{prefix}/docs        Scalar API reference
 *   GET /{prefix}/docs-json   OpenAPI JSON
 *   GET /{prefix}/docs-yaml   OpenAPI YAML
 *
 * Must be called before the global helmet() middleware: the docs page sends its own CSP that
 * allows the pinned Scalar bundle via a per-request nonce, while every other route keeps
 * helmet's strict default policy.
 */
export function setupApiDocs(app: NestExpressApplication, prefix: string): void {
  const config = new DocumentBuilder()
    .setTitle('Cargo API')
    .setDescription(
      'Air & sea freight forwarding API: customers, airports/seaports, carriers, shipments, containers and tracking.',
    )
    .setVersion(process.env.npm_package_version ?? '1.0.0')
    .addBearerAuth()
    .build();
  const document = SwaggerModule.createDocument(app, config);

  // Spec endpoints only; Scalar replaces the bundled Swagger UI.
  SwaggerModule.setup(`${prefix}/docs`, app, document, {
    ui: false,
    jsonDocumentUrl: `${prefix}/docs-json`,
    yamlDocumentUrl: `${prefix}/docs-yaml`,
  });

  const scalarConfig = JSON.stringify({
    url: `/${prefix}/docs-json`,
    persistAuth: true,
    // Hide Scalar's hosted-platform features: the localhost toolbar/promo and the chat assistant
    // (which would send the spec to Scalar's servers; the CSP blocks it anyway).
    showDeveloperTools: 'never',
    agent: { disabled: true },
    defaultHttpClient: { targetKey: 'node', clientKey: 'fetch' },
  }).replace(/</g, '\\u003c');

  app.getHttpAdapter().get(`/${prefix}/docs`, (_req: Request, res: Response) => {
    const nonce = randomBytes(16).toString('base64');
    res.set({
      'Content-Type': 'text/html; charset=utf-8',
      'Content-Security-Policy': [
        "default-src 'self'",
        `script-src 'nonce-${nonce}'`,
        // Scalar injects component styles at runtime.
        "style-src 'self' 'unsafe-inline'",
        "font-src 'self' data: https://fonts.scalar.com",
        "img-src 'self' data: https:",
        "connect-src 'self'",
        "object-src 'none'",
        "base-uri 'none'",
        "form-action 'none'",
        "frame-ancestors 'none'",
      ].join('; '),
      'Cache-Control': 'no-store',
      'Referrer-Policy': 'no-referrer',
      'X-Content-Type-Options': 'nosniff',
    }).send(`<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Cargo API Reference</title>
  </head>
  <body>
    <div id="app"></div>
    <script src="${SCALAR_BUNDLE.src}" integrity="${SCALAR_BUNDLE.integrity}" crossorigin="anonymous" nonce="${nonce}"></script>
    <script nonce="${nonce}">Scalar.createApiReference('#app', ${scalarConfig});</script>
  </body>
</html>`);
  });
}
